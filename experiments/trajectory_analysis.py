def _istarmap(self, func, iterable, chunksize=1):
    """starmap-version of imap"""
    self._check_running()
    if chunksize < 1:
        raise ValueError(
            "Chunksize must be 1+, not {0:n}".format(
                chunksize))

    task_batches = mpp.Pool._get_tasks(func, iterable, chunksize)
    result = mpp.IMapIterator(self)
    self._taskqueue.put(
        (
            self._guarded_task_generation(result._job,
                                          mpp.starmapstar,
                                          task_batches),
            result._set_length
        )
    )
    return (item for chunk in result for item in chunk)


def _spherical_distance_vectorized(traj, shortest_route):
    """Vectorized version of spherical_distance"""
    traj = np.asarray(traj)
    shortest_route = np.asarray(shortest_route)
    
    lon1 = traj[:, 0][:, np.newaxis]
    lat1 = traj[:, 1][:, np.newaxis]
    lon2 = shortest_route[:, 0][np.newaxis, :]
    lat2 = shortest_route[:, 1][np.newaxis, :]
    
    R = 6371000
    
    rlon1 = lon1 * np.pi / 180.0
    rlon2 = lon2 * np.pi / 180.0  
    rlat1 = lat1 * np.pi / 180.0
    rlat2 = lat2 * np.pi / 180.0
    dlon = (rlon1 - rlon2) / 2.0
    dlat = (rlat1 - rlat2) / 2.0
    lat12 = (rlat1 + rlat2) / 2.0
    sindlat = np.sin(dlat)
    sindlon = np.sin(dlon)
    cosdlon = np.cos(dlon)
    coslat12 = np.cos(lat12)
    f = sindlat * sindlat * cosdlon * cosdlon + sindlon * sindlon * coslat12 * coslat12
    f = np.sqrt(f)
    f = np.arcsin(f) * 2.0  # the angle between the points
    f *= R

    return f


def _get_path(predecessors, source_idx, target_idx):
    """Return the path generated by SciPy's Dijkstra"""
    path = []
    current = target_idx

    while current != -9999 and current != source_idx:
        path.append(current)
        current = predecessors[current]
        
    if current == source_idx:
        path.append(source_idx)
        return path[::-1]
    
    return None


