def get_route_bbox(G, routes, buffer=0.01):
    # return a bbox that contains multiple routes with some padding
    lats = []
    lons = []
    for route in routes:
        lats.extend([G.nodes[i]['y'] for i in route])
        lons.extend([G.nodes[i]['x'] for i in route])
        
    # bbox is left, bottom, right, top
    return (min(lons) - buffer, min(lats) - buffer, max(lons) + buffer, max(lats) + buffer)


def plot_trajectory_on_map(G, routes, uid, tid, optimize: list[str]):
    """
    Plot a route of the graph, along with the optimal routes that minimize
    different metrics that connect the original route's origin and destination.
    """
    real_route = routes[uid][tid]['nodes']

    routes_to_plot = [real_route]
    legend_names = ['Real route']

    if 'random' in optimize:
        nodes, edges = ox.graph_to_gdfs(G, nodes=True, edges=True)
        edges['random_weight'] = np.random.choice(100, len(edges))
        G_copy = ox.graph_from_gdfs(nodes, edges)

        shortest_route = nx.shortest_path(G_copy, real_route[0], real_route[-1], weight='random_weight')
        routes_to_plot.append(shortest_route)
        legend_names.append('Random route')
    if 'time' in optimize:
        fastest_route = nx.shortest_path(G, real_route[0], real_route[-1], weight='travel_time')
        routes_to_plot.append(fastest_route)
        legend_names.append('Travel time')
    if 'distance' in optimize:
        optimal_dist = nx.shortest_path(G, real_route[0], real_route[-1], weight='length')
        routes_to_plot.append(optimal_dist)
        legend_names.append('Length')
    if 'speed' in optimize:
        speed_route = nx.shortest_path(G, real_route[0], real_route[-1], weight='speed_kph')
        routes_to_plot.append(speed_route)
        legend_names.append('Speed limit')
    if 'residential' in optimize:
        residential_route = nx.shortest_path(G, real_route[0], real_route[-1], weight='residential')
        routes_to_plot.append(residential_route)
        legend_names.append('Residential')
    if 'motorway' in optimize:
        motorway_route = nx.shortest_path(G, real_route[0], real_route[-1], weight='motorway')
        routes_to_plot.append(motorway_route)
        legend_names.append('Motorway')

    route_colors = plt.cm.rainbow(np.linspace(0, 1, len(routes_to_plot)))
    ox.plot_graph_routes(G,
                         routes=routes_to_plot,
                         bgcolor='#ffffff',
                         edge_color='#808080',
                         edge_linewidth=0.25,
                         route_colors=route_colors,
                         route_linewidth=2,
                         route_alpha=0.5,
                         node_size=0,
                         bbox=get_route_bbox(G, routes_to_plot),
                         close=False,
                         show=False)

    plt.legend(handles=[plt.Line2D([0],[0], color=c, lw=2, alpha=0.5) for c in route_colors],
               labels=legend_names,
               loc='upper left',
               fontsize='small')
    
    plt.show()