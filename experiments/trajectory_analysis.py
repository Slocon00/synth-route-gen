def dtw_overlap_routes(G: nx.MultiDiGraph, route1: list, route2: list) -> tuple:
    """
    Calculate the Dynamic Time Warping distance and overlap between two routes.

    Parameters
    ----------
    G : nx.MultiDiGraph
        The osmnx graph on which the routes are defined.
    route1 : list
        The first route, represented as a list of graph node IDs.
    route2 : list
        The second route, represented as a list of graph node IDs.

    Returns
    -------
    dtw_distance : float
        The DTW distance between the two routes.
    overlap : float
        The overlap between the two routes, calculated as the ratio of common nodes
        to the total number of nodes in the longer route.
    """
    route1_coords = [(G.nodes[node]['x'], G.nodes[node]['y']) for node in route1]
    route2_coords = [(G.nodes[node]['x'], G.nodes[node]['y']) for node in route2]
    path, sim = dtw_path_from_metric(
        _spherical_distance_vectorized(route1_coords, route2_coords),
        metric='precomputed'
    )
    dtw_distance = float(sim/len(path))

    common_nodes = set(route1).intersection(set(route2))
    union_nodes = set(route1).union(set(route2))
    overlap = len(common_nodes) / len(union_nodes)

    return dtw_distance, overlap


def _worker_dtw_overlap(uid: int, user_routes: dict):
    """
    Worker function to compute DTW distance and overlap for a user's routes
    against optimal routes based on different cost metrics.
    
    Parameters
    ----------
    uid : int
        User ID for which the DTW and overlap metrics are computed.
    user_routes : dict
        A dictionary containing the user's routes.
    
    Returns
    -------
    uid : int
        The user ID (to reconstruct the results).
    tid_to_stats : dict
        A dictionary mapping trajectory IDs to their corresponding DTW and
        overlap metrics.
    """
    orig_indices = []
    dest_indices = []
    trajs = []
    for tid, route_data in user_routes.items():
        route = route_data['nodes']

        origin = (G_WORKER.nodes[route[0]]['x'], G_WORKER.nodes[route[0]]['y'])
        destination = (G_WORKER.nodes[route[-1]]['x'], G_WORKER.nodes[route[-1]]['y'])
        if spherical_distance(origin, destination) < 500:
            # Skip self loops and routes that are too short
            continue
        
        trajs.append((tid, route))

        orig_idx = NODE_TO_IDX[route[0]]
        dest_idx = NODE_TO_IDX[route[-1]]

        orig_indices.append(orig_idx)
        dest_indices.append(dest_idx)
    
    tid_to_stats = {tid: {} for tid, _ in trajs}
    for i, cost in enumerate(['travel_time', 'length', 'speed_kph', 'residential', 'motorway', 'random']):
        adj_matrix = coo_matrix((ATTRIBUTE_VALUES[i], (U_INDICES, V_INDICES)), shape=(N_NODES, N_NODES))
        _, predecessors = dijkstra(
            adj_matrix,
            directed=True,
            indices=orig_indices,
            return_predecessors=True
        )

        for j, (orig_idx, dest_idx) in enumerate(zip(orig_indices,dest_indices)):
            path_indices = _get_path(predecessors[j], orig_idx, dest_idx)
            opt_route = [IDX_TO_NODE[k] for k in path_indices]

            dtw, overlap = dtw_overlap_routes(G_WORKER, trajs[j][1], opt_route)
            tid_to_stats[trajs[j][0]]['dtw_' + cost] = dtw
            tid_to_stats[trajs[j][0]]['overlap_' + cost] = overlap
            
            origin = G_WORKER.nodes[opt_route[0]]['x'], G_WORKER.nodes[opt_route[0]]['y']
            destination = G_WORKER.nodes[opt_route[-1]]['x'], G_WORKER.nodes[opt_route[-1]]['y']
            dist_o_d = spherical_distance(origin, destination)
            tid_to_stats[trajs[j][0]]['spherical_dist_o_d'] = dist_o_d

    return uid, tid_to_stats


def dtw_overlap_all(G: nx.MultiDiGraph, routes: dict, filename: str, num_processes: int = None, verbose: bool = False):
    """
    Compute and write to file the dynamic time warping distance and the overlap
    between each trajectory in `routes` and a set of optimal routes that minimize
    different metrics, for all users in the provided data.

    Parameters
    ----------
    G : nx.MultiDiGraph
        The osmnx graph on which to compute the shortest paths.
    routes : dict
        A dictionary mapping each user ID to a dictionary of map-matched and
        recontructed trajectories, containing a list of graph nodes (`nodes`).
    filename : str
        The path to the output CSV file the similarities will be saved to.
    num_processes : int, optional
        Number of processes to use for parallel computation. If None, the
        number of CPU cores will be used. Defaults to None.
    verbose: bool, optional
        Controls whether to display a progress bar during processing.
    """
    nodes = list(G.nodes())
    node_to_idx = {node: i for i, node in enumerate(nodes)}
    idx_to_node = {i: node for i, node in enumerate(nodes)}

    edges = list(G.edges(data=True))
    u_indices = np.array([node_to_idx[u] for u, _, _ in edges])
    v_indices = np.array([node_to_idx[v] for _, v, _ in edges])

    attribute_values = []
    for attr in ['travel_time', 'length', 'speed_kph', 'residential', 'motorway']:
        if attr in ['residential', 'motorway']:
            attribute_values.append(np.array([1-d[attr] for _, _, d in edges]))
        else:
            attribute_values.append(np.array([d[attr] for _, _, d in edges]))
    attribute_values.append(np.random.choice(100, len(edges)))  # for random cost
    attribute_values = np.array(attribute_values)

    n_nodes = len(G.nodes)

    mpp.Pool.istarmap = _istarmap
    pool = mpp.Pool(processes=num_processes,
                    initializer=_init_global_variables,
                    initargs=(G,
                              n_nodes,
                              node_to_idx,
                              idx_to_node,
                              u_indices,
                              v_indices,
                              attribute_values)
    )
    
    costs = ['travel_time', 'length', 'speed_kph', 'residential', 'motorway', 'random']
    with open(filename, 'w') as fout:
        # TODO change to gz
        writer = csv.writer(fout)
        header = ['uid', 'tid'] + [f'dtw_{cost}' for cost in costs] + [f'overlap_{cost}' for cost in costs] + ['spherical_dist_o_d']
        writer.writerow(header)

        for uid, tid_to_stats in list(tqdm.tqdm(pool.istarmap(_worker_dtw_overlap,
                                                              [(uid, user_routes) for uid, user_routes in routes.items()]),
                                                              total=len(routes),
                                                              desc='Users',
                                                              disable=not verbose)):
            for tid in tid_to_stats.keys():
                row = [uid, tid]

                # First all dtw then all overlaps
                for cost in costs:
                    row.append(tid_to_stats[tid]['dtw_' + cost])
                for cost in costs:
                    row.append(tid_to_stats[tid]['overlap_' + cost])
                row.append(tid_to_stats[tid]['spherical_dist_o_d'])
                writer.writerow(row)
        
        pool.close()
        pool.join()


