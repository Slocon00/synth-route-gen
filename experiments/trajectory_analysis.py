def _worker_collect_user_attributes(uid: int,
                                   user_routes: dict,
                                   user_alphas: dict,
                                   betas=None):
    """
    Worker function that collects a user's edge attributes.
    
    Parameters
    ----------
    uid: int
        User ID for which attributes are collected.
    user_routes: dict
        A dictionary containing the user's routes.
    user_alphas: dict
        A dictionary containing the user's alpha values to use in the cost
        function.
    betas: dict, optional
        A dictionary containing the beta values to use in the cost function.
        If `None` (default), the passed betas will be used. Otherwise, a fixed
        global set of betas is used instead.

    Returns
    -------
    uid: int
        The user ID (to reconstruct the results).
    user_values: dict
        A dictionary mapping each attribute to a list of values collected from
        the user's routes.
    """
    user_values = {}
    
    user_costs = ATTRIBUTE_VALUES[attributes.index('travel_time')].copy()
    for attr in COST_ATTRIBUTES:
        w = (np.exp(1 - user_alphas[attr]) - 1)
        if betas is not None:
            beta = betas[COST_ATTRIBUTES.index(attr)]
        else:
            beta = BETA
        user_costs += beta * w * ATTRIBUTE_VALUES[attributes.index(attr)]
    user_costs = BASE_COST * (1 + user_costs)
    user_costs[user_costs <= 0] = 0.0

    adj_matrix = coo_matrix((user_costs, (U_INDICES, V_INDICES)), shape=(N_NODES, N_NODES))

    orig_indices = []
    dest_indices = []
    for _, route_data in user_routes.items():
        route = route_data['nodes']

        origin = (G_WORKER.nodes[route[0]]['x'], G_WORKER.nodes[route[0]]['y'])
        destination = (G_WORKER.nodes[route[-1]]['x'], G_WORKER.nodes[route[-1]]['y'])
        if spherical_distance(origin, destination) < 500:
            continue
        
        orig_idx = NODE_TO_IDX[route[0]]
        dest_idx = NODE_TO_IDX[route[-1]]

        orig_indices.append(orig_idx)
        dest_indices.append(dest_idx)
  
    _, predecessors = dijkstra(
        adj_matrix,
        directed=True,
        indices=orig_indices,
        return_predecessors=True
    )

    for i, (orig_idx, dest_idx) in enumerate(zip(orig_indices,dest_indices)):
        path_indices = _get_path(predecessors[i], orig_idx, dest_idx)
        opt_route = [IDX_TO_NODE[i] for i in path_indices]

        for node1, node2 in zip(opt_route, opt_route[1:]):
            data = G_WORKER.get_edge_data(node1, node2, 0)

            for attr in attributes:
                value = data.get(attr, 0)
                if attr not in user_values: user_values[attr] = []
                user_values[attr].append(np.float64(value))

    return uid, user_values


def get_local_adjusted_edge_attributes(G: nx.MultiDiGraph,
                                             routes: dict,
                                             beta: float,
                                             cost_attributes: list[str],
                                             filename_adjusted: str,
                                             filename_alphas: str,
                                             num_processes: int = None,
                                             verbose=False):
    """
    Compute and write to file the edge attributes of the optimal routes for
    each user in `routes`, based on their individual alpha values and a 
    single global beta value.

    Parameters
    ----------
    G : nx.MultiDiGraph
        The osmnx graph on which the routes are defined.
    routes : dict
        A dictionary mapping each user ID to a dictionary of map-matched and
        recontructed trajectories, containing a list of graph nodes (`nodes`).
    beta : float
        The global beta value to use in the cost function.
    cost_attributes : list of str
        A list of edge attributes to use in the cost function.
    filename_adjusted : str
        The path to the output CSV file where the adjusted routes' edge attributes
        will be saved.
    filename_alphas : str
        The path to the JSON file containing the alpha values for each user.
    num_processes : int, optional
        Number of processes to use for parallel computation. If None, the
        number of CPU cores will be used. Defaults to None.
    verbose: bool, optional
        Controls whether to display a progress bar during processing.
    """

    nodes = list(G.nodes())
    node_to_idx = {node: i for i, node in enumerate(nodes)}
    idx_to_node = {i: node for i, node in enumerate(nodes)}

    edges = list(G.edges(data=True))
    u_indices = np.array([node_to_idx[u] for u, _, _ in edges])
    v_indices = np.array([node_to_idx[v] for _, v, _ in edges])

    attribute_values = []
    for attr in attributes:
        attribute_values.append(np.array([d[attr] for _, _, d in edges]))
    attribute_values = np.array(attribute_values)

    base_cost = np.nanmedian(attribute_values[attributes.index('travel_time')])

    scaler = MaxAbsScaler()
    attribute_values = scaler.fit_transform(attribute_values)

    n_nodes = len(G.nodes)

    mpp.Pool.istarmap = _istarmap
    pool = mpp.Pool(processes=num_processes,
                    initializer=_init_global_variables,
                    initargs=(G,
                              n_nodes,
                              node_to_idx,
                              idx_to_node,
                              u_indices,
                              v_indices,
                              attribute_values,
                              attributes,
                              cost_attributes,
                              base_cost,
                              beta)
    )

    ratios = json.load(open(filename_alphas, 'r'))
    with gzip.open(filename_adjusted, 'wb') as f_adjusted:
        columns = ['uid'] + attributes
        f_adjusted.write(','.join(columns).encode() + b'\n')

        for uid, user_values in list(tqdm.tqdm(pool.istarmap(_worker_collect_user_attributes,
                                                             [(uid,
                                                               user_routes,
                                                               ratios[str(uid)]) for uid, user_routes in routes.items()]),
                                                               total=len(routes),
                                                               desc='Users',
                                                               disable=not verbose)
                                    ):    
            row = f'{uid}'
            for attr in attributes:
                row += f',{np.nanmean(user_values[attr])}'
            f_adjusted.write(row.encode() + b'\n')

    pool.close()
    pool.join()


