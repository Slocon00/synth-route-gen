def get_route_edge_attributes(G: nx.MultiDiGraph,
                              routes: dict,
                              center: dict,
                              filename_real: str,
                              filename_fastest: str,
                              verbose: bool = False):
    """
    Collect the edge attributes of all the routes traversed by the users in
    `routes` over the graph `G`. The function will compute both the attributes
    of the real traversed routes and the corresponding fastest routes. Each
    record will also include some additional temporal information (weekday,
    hour) and spatial information (o-d distance, distances with the center).


    Parameters
    ----------
    G : nx.MultiDiGraph
        The osmnx graph on which the routes are defined.
    routes : dict
        A dictionary mapping each user ID to a dictionary of map-matched and
        recontructed trajectories, containing a list of graph nodes (`nodes`).
    center : dict
        The center of the city/region covered by the data. It is not necessarily
        the geometric center of the graph. Must contain the keys 'x' and 'y'
        for longitude and latitude, respectively.
    filename_real : str
        The path to the output CSV file where the real routes' edge attributes
        will be saved.
    filename_fastest : str
        The path to the output CSV file where the fastest routes' edge attributes
        will be saved.
    verbose: bool, optional
        Controls whether to display a progress bar during processing.
    """
    # TODO parallelize
    weekday_names = {
        0: 'Monday',
        1: 'Tuesday',
        2: 'Wednesday',
        3: 'Thursday',
        4: 'Friday',
        5: 'Saturday',
        6: 'Sunday'
    }
    
    nodes = list(G.nodes())
    node_to_idx = {node: i for i, node in enumerate(nodes)}
    idx_to_node = {i: node for i, node in enumerate(nodes)}

    edges = list(G.edges(data=True))
    u_indices = np.array([node_to_idx[u] for u, _, _ in edges])
    v_indices = np.array([node_to_idx[v] for _, v, _ in edges])

    attribute_values = []
    for attr in attributes:
        attribute_values.append(np.array([d[attr] for _, _, d in edges]))
    attribute_values = np.array(attribute_values)

    n_nodes = len(G.nodes)

    adj_matrix = coo_matrix((attribute_values[attributes.index('travel_time')].copy(),
                             (u_indices, v_indices)),
                             shape=(n_nodes, n_nodes))

    with gzip.open(filename_real, 'wb') as f_real, gzip.open(filename_fastest, 'wb') as f_fastest:
        columns = ['uid',
                   'tid',
                   'start_weekday',
                   'start_hour',
                   'route_dist_o_d',
                   'route_dist_o_center',
                   'route_dist_d_center',
                   'edge_dist_center'
                   ] + attributes

        f_real.write(','.join(columns).encode() + b'\n')
        f_fastest.write(','.join(columns).encode() + b'\n')

        for uid, user_routes in tqdm.tqdm(routes.items(), desc='Users', disable=not verbose):
            for tid, route_data in user_routes.items():
                route = route_data['nodes']

                origin = (G.nodes[route[0]]['x'], G.nodes[route[0]]['y'])
                destination = (G.nodes[route[-1]]['x'], G.nodes[route[-1]]['y'])
                center_point = (center['x'], center['y'])
                if spherical_distance(origin, destination) < 500:
                    continue
                
                start = route_data['start_timestamp']
                start_hour = datetime.datetime.fromtimestamp(start).hour
                start_weekday = weekday_names[datetime.datetime.fromtimestamp(start).weekday()]

                orig_idx = node_to_idx[route[0]]
                dest_idx = node_to_idx[route[-1]]

                route_dist_o_d = spherical_distance(origin, destination)
                route_dist_o_center = spherical_distance(origin, center_point)
                route_dist_d_center = spherical_distance(destination, center_point)

                for node1, node2 in zip(route, route[1:]):
                    centroid = ((G.nodes[node1]['x'] + G.nodes[node2]['x']) / 2,
                                (G.nodes[node1]['y'] + G.nodes[node2]['y']) / 2)
                    edge_dist_center = spherical_distance(centroid, center_point)
                    data = G.get_edge_data(node1, node2, 0)

                    row = []
                    for attr in attributes:
                        value = data.get(attr, 0)
                        try:
                            row.append(np.float64(value))
                        except:
                            row.append(value)
                    # TODO rewrite string in a nicer way
                    f_real.write((f'{uid},{tid},{start_weekday},{start_hour},{route_dist_o_d},{route_dist_o_center},{route_dist_d_center},{edge_dist_center},' + ','.join(map(str, row))).encode() + b'\n')

                _, predecessors = dijkstra(
                    adj_matrix,
                    directed=True,
                    indices=orig_idx,
                    return_predecessors=True
                )

                path_indices = _get_path(predecessors, orig_idx, dest_idx)
                opt_route = [idx_to_node[i] for i in path_indices]

                for node1, node2 in zip(opt_route, opt_route[1:]):
                    centroid = ((G.nodes[node1]['x'] + G.nodes[node2]['x']) / 2,
                                (G.nodes[node1]['y'] + G.nodes[node2]['y']) / 2)
                    edge_dist_center = spherical_distance(centroid, center_point)
                    data = G.get_edge_data(node1, node2, 0)

                    row = []
                    for attr in attributes:
                        value = data.get(attr, 0)
                        try:
                            row.append(np.float64(value))
                        except:
                            row.append(value)
                    f_fastest.write((f'{uid},{tid},{start_weekday},{start_hour},{route_dist_o_d},{route_dist_o_center},{route_dist_d_center},{edge_dist_center},' + ','.join(map(str, row))).encode() + b'\n')


